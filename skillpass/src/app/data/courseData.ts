export type SurveyQuestionType =
  | 'short_text'
  | 'long_text'
  | 'single_choice'
  | 'multiple_choice'
  | 'scale_1_5'
  | 'yes_no';

export interface SurveyQuestion {
  id: number;
  type: SurveyQuestionType;
  title: string;
  description?: string;
  options?: string[];
}

export interface Survey {
  title: string;
  description?: string;
  questions: SurveyQuestion[];
}

export interface Lesson {
  id: number;
  title: string;
  description: string;
  videoUrl?: string;
  presentationUrl?: string;
  pdfUrl?: string;
  longread?: string;
  resources?: Resource[];
  survey?: Survey;
}

export interface Topic {
  id: number;
  title: string;
  description: string;
  lessons: Lesson[];
}

